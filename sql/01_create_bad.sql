-- Шаг 1. Создание базы orders_norm и «плохой» таблицы orders_bad
-- (заказы, клиенты, товары и представители в одной плоской таблице)
-- ============================================================

DROP DATABASE IF EXISTS orders_norm;
CREATE DATABASE orders_norm
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE orders_norm;

-- «Плохая» (ненормализованная) таблица: одна плоская таблица,
-- в которой смешаны шапка заказа, товар, его цена и представитель
CREATE TABLE orders_bad (
    order_id     INT,
    order_date   DATE,
    customer_id  INT,
    product_id   INT,
    product_name VARCHAR(100),
    price        DECIMAL(10,2),
    rep_id       INT,
    rep_name     VARCHAR(100),
    quantity     INT
);

