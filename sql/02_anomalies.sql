-- ============================================================
-- Шаг 2. Демонстрация трёх аномалий «плохой» таблицы
-- Каждая демонстрация откатывается (ROLLBACK), данные не портятся
-- ============================================================

USE orders_norm;

SET autocommit = 0;

-- ------------------------------------------------------------
-- АНОМАЛИЯ 1: АНОМАЛИЯ ОБНОВЛЕНИЯ (UPDATE ANOMALY)
-- ------------------------------------------------------------
-- Представитель 1 «Соколов Артём» встречается в 4 строках.
-- Чтобы исправить имя, придётся обновить ВСЕ эти строки.
-- Если обновить не все — в таблице останутся противоречивые данные.

SELECT COUNT(*) AS rows_of_rep_1
FROM orders_bad
WHERE rep_id = 1;

-- Придётся обновить сразу 4 строки одним запросом:
UPDATE orders_bad
SET rep_name = 'Соколов А. В.'
WHERE rep_id = 1;

-- А если ошибиться и обновить только часть строк (только один заказ),
-- данные станут ПРОТИВОРЕЧИВЫМИ: у одного представителя два имени
UPDATE orders_bad
SET rep_name = 'Соколов Артём'
WHERE rep_id = 1 AND order_id = 5001;

SELECT rep_id, rep_name, COUNT(*) AS cnt
FROM orders_bad
GROUP BY rep_id, rep_name;

ROLLBACK;  -- отменяем демо-изменения

-- ------------------------------------------------------------
-- АНОМАЛИЯ 2: АНОМАЛИЯ ВСТАВКИ (INSERT ANOMALY)
-- ------------------------------------------------------------
-- Нельзя добавить НОВОГО представителя или товар, пока нет заказа:
-- приходится вставлять бессмысленные NULL в несвязанные поля.
-- Нельзя и «навесить» второго представителя на существующий заказ:
-- пришлось бы дублировать шапку заказа в новых строках.

-- Попытка завести представителя 4 «Кузнецов Игорь» без заказа:
INSERT INTO orders_bad
    (order_id, order_date, customer_id, product_id,
     product_name, price, rep_id, rep_name, quantity)
VALUES (NULL, NULL, NULL, NULL, NULL, NULL, 4, 'Кузнецов Игорь', NULL);

SELECT * FROM orders_bad WHERE rep_id = 4;

ROLLBACK;  -- отменяем демо-вставку

-- ------------------------------------------------------------
-- АНОМАЛИЯ 3: АНОМАЛИЯ УДАЛЕНИЯ (DELETE ANOMALY)
-- ------------------------------------------------------------
-- Удалим заказ 5003 — единственный заказ с товаром 205 «Флешка».
-- Вместе с ним НЕОБРАТИМО теряется информация, что вообще
-- существует товар 205 «Флешка» с ценой 900.

DELETE FROM orders_bad
WHERE order_id = 5003;

-- Строк заказа 5003 больше нет:
SELECT * FROM orders_bad WHERE order_id = 5003;

-- Товар 205 «Флешка» исчез из таблицы полностью:
SELECT DISTINCT product_id, product_name, price
FROM orders_bad
WHERE product_id = 205;

ROLLBACK;  -- отменяем демо-удаление

-- Возвращаем автокоммит
SET autocommit = 1;

-- Итоговая проверка: данные на месте (ROLLBACK-и всё вернули)
SELECT * FROM orders_bad ORDER BY order_id, product_id;
